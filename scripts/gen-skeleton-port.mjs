// Builds the skeleton-port project template: the skeleton's working screens, without its sample game.
//
// Porting a finished game into Studio starts from the skeleton, because its pages are already wired
// to saving, loading, settings and the backlog. Everything else the skeleton ships - three scenes of
// story, two characters, the backgrounds, the music and the sprite they use - is a sample, and a port
// spends its first steps deleting it, or working around it when it is not deleted (a scene that sets
// no background of its own shows the sample's). This template is the skeleton with that sample taken
// out, so a port starts from the screens alone.
//
// It is generated, never edited: the skeleton changes often, and a second copy kept by hand would
// fall behind it the first time a page was touched. Everything structural is copied from the
// skeleton's three content trees (`content/`, `content.zh/`, `content.ja/`) unchanged, and what is
// removed is decided by what the interface reads rather than by a list of names:
//   - an asset stays when the interface or the palette names it (the title's key art, the three
//     interface sounds), and every other one goes, with its file and any asset group left empty;
//   - a variable stays when the interface names it (the place a save slot shows), and the rest go;
//   - the story keeps its entry scene, under its id, because the title's Start blueprint names that
//     id - emptied, renamed, and with no background of its own - and loses every other scene;
//   - every character goes;
//   - the translation files lose the units of everything removed, and the entry scene's unit is
//     rewritten for its new name.
// A unit of a kind this script does not know fails the run rather than being copied or dropped
// without a decision.
//
// Run after the skeleton changes (after `gen-skeleton-locale.mjs`, which writes the trees read here):
//   node scripts/gen-skeleton-port.mjs
// Verify the committed template matches:
//   node scripts/gen-skeleton-port.mjs --check

import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SOURCE_DIR = resolve(HERE, "../resources/templates/skeleton");
const TARGET_DIR = resolve(HERE, "../resources/templates/skeleton-port");

/** The entry scene's name in each language a tree or a translation file is written in. */
const ENTRY_SCENE_NAMES = { en: "Start", zh: "开始", ja: "開始" };
const ENTRY_SCENE_RUNTIME_NAME = "start";

const MANIFEST_TEXT = {
    name: "Skeleton (screens only)",
    description: "The skeleton's working screens - splash, title, extra, save, load, config, backlog and confirm, with their blueprints wired - and one empty scene. No sample story, characters or art: for porting a finished game.",
    locales: {
        zh: {
            name: "骨架（仅界面）",
            description: "骨架的全部可用界面：启动画面、标题、鉴赏、存档、读档、设置、记录与确认，蓝图都已接好；只带一个空场景，不含示例剧情、角色和素材，用于迁移已完成的作品",
        },
        ja: {
            name: "スケルトン（画面のみ）",
            description: "スケルトンの動作する画面一式（スプラッシュ・タイトル・鑑賞・セーブ・ロード・設定・履歴・確認、ブループリント接続済み）と空のシーン一つ。サンプルの物語・キャラクター・素材は含まず、完成した作品の移植向け",
        },
    },
};

const README = `# Skeleton (screens only)

Generated by \`scripts/gen-skeleton-port.mjs\` from \`../skeleton/\`. Do not edit anything here by hand:
change the skeleton, then run the script again (\`--check\` verifies this directory matches).

The files in \`content/assets/\` are a subset of the skeleton's; their provenance and licences are in
\`../skeleton/CREDITS.md\`.
`;

const STORY_DOC = /^editor\/story\/stories\/[^/]+\/storydoc\.json$/;
const ASSET_METADATA = /^assets\/assets\.metadata\.[^.]+\.json$/;
const ASSET_ORDER = /^assets\/assets\.order\.[^.]+\.json$/;
const ASSET_GROUPS = /^assets\/assets\.groups\.[^.]+\.json$/;
const ASSET_CONTENT = /^assets\/content\/([0-9a-f]{2})\/([0-9a-f]{2})\/([0-9a-f]+)$/;
const TRANSLATION = /^editor\/localization\/([^/]+)\.json$/;
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

function listFiles(dir, base = dir) {
    const out = [];
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
        const full = join(dir, entry.name);
        if (entry.isDirectory()) {
            out.push(...listFiles(full, base));
        } else {
            out.push(relative(base, full).split("\\").join("/"));
        }
    }
    return out;
}

function readJson(file) {
    return JSON.parse(readFileSync(file, "utf-8"));
}

/** As Studio writes JSON, so a file this script did not change round-trips byte for byte. */
function sameFormatJson(original, value) {
    const indent = /^\{\r?\n( +|\t)/.exec(original)?.[1] ?? "";
    const text = JSON.stringify(value, null, indent || undefined);
    return original.endsWith("\n") ? `${text}\n` : text;
}

/** FNV-1a over UTF-16 code units - the same hash `shared/utils/localizationText` stamps units with. */
function hashSourceText(text) {
    let hash = 0x811c9dc5;
    for (let i = 0; i < text.length; i++) {
        hash ^= text.charCodeAt(i);
        hash = Math.imul(hash, 0x01000193);
    }
    return `fnv1a:${(hash >>> 0).toString(16).padStart(8, "0")}`;
}

/** The language a translation file is written in, from its name (`zh-CN.json` → `zh`). */
function languageOfFile(name) {
    const language = name.split("-")[0];
    if (!(language in ENTRY_SCENE_NAMES)) {
        throw new Error(`no entry scene name for the language of editor/localization/${name}.json`);
    }
    return language;
}

/** Ids the interface itself names: everything it reads and nothing it does not survives the trim. */
function interfaceText(treeDir) {
    return ["editor/ui/uidoc.json", "editor/ui/uigraphs.json", "editor/brand.json"]
        .map(file => readFileSync(join(treeDir, file), "utf-8"))
        .join("\n");
}

function assetContentId(match) {
    const [, a, b, rest] = match;
    const hex = a + b + rest;
    return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

/** Every `textId` in a story document: the ids its lines and choices are translated under. */
function collectTextIds(value, out) {
    if (Array.isArray(value)) {
        value.forEach(item => collectTextIds(item, out));
    } else if (value && typeof value === "object") {
        for (const [key, item] of Object.entries(value)) {
            if (key === "textId" && typeof item === "string") {
                out.add(item);
            } else {
                collectTextIds(item, out);
            }
        }
    }
}

/** Decide, once from the English tree, what the template keeps. Every tree shares the ids. */
function planTrim() {
    const base = join(SOURCE_DIR, "content");
    const ui = interfaceText(base);

    const assets = new Map();
    for (const file of listFiles(base).filter(path => ASSET_METADATA.test(path))) {
        for (const record of Object.values(readJson(join(base, file)))) {
            assets.set(record.id, record);
        }
    }
    const keptAssets = new Set([...assets.keys()].filter(id => ui.includes(id)));
    const keptGroups = new Set([...keptAssets].map(id => assets.get(id).groupId).filter(Boolean));

    const variables = readJson(join(base, "editor/variables.json")).entries;
    const keptVariables = new Set(Object.keys(variables).filter(id => ui.includes(id)));

    const storyFile = listFiles(base).find(path => STORY_DOC.test(path));
    const story = readJson(join(base, storyFile));
    const entrySceneId = story.entrySceneId;
    if (!ui.includes(entrySceneId)) {
        // The reason the entry scene is kept under its id is that the title names it. If that stops
        // being so, the rule here needs a second look rather than a silent carry-on.
        throw new Error(`the skeleton's interface no longer names its entry scene ${entrySceneId}`);
    }
    const storyTexts = new Set();
    collectTextIds(story, storyTexts);
    const characters = readJson(join(base, "editor/services/character.json")).characters.map(entry => entry.profile.id);

    return { keptAssets, keptGroups, keptVariables, entrySceneId, storyTexts, characters: new Set(characters) };
}

function trimStory(story, plan, language) {
    const entry = story.scenes[plan.entrySceneId];
    const { defaultBackgroundAssetId: _background, ...rest } = entry;
    story.scenes = {
        [plan.entrySceneId]: {
            ...rest,
            name: ENTRY_SCENE_NAMES[language],
            runtimeName: ENTRY_SCENE_RUNTIME_NAME,
            rootBlockIds: [],
            blocks: {},
        },
    };
    story.chapters = story.chapters
        .filter(chapter => chapter.sceneIds.includes(plan.entrySceneId))
        .map(chapter => ({ ...chapter, sceneIds: [plan.entrySceneId] }));
    return story;
}

function trimTranslation(document, plan, treeLanguage, fileLanguage) {
    const units = {};
    for (const [id, unit] of Object.entries(document.units)) {
        if (id.startsWith("key:") || id.startsWith("ui:")) {
            units[id] = unit;
        } else if (id.startsWith("scene:")) {
            if (id === `scene:${plan.entrySceneId}`) {
                units[id] = {
                    ...unit,
                    sourceHash: hashSourceText(ENTRY_SCENE_NAMES[treeLanguage]),
                    target: ENTRY_SCENE_NAMES[fileLanguage],
                };
            }
        } else if (id.startsWith("char:")) {
            if (!plan.characters.has(id.slice("char:".length))) {
                throw new Error(`translation unit ${id} names no character the skeleton has`);
            }
        } else if (UUID.test(id) && plan.storyTexts.has(id)) {
            // A line of the sample story.
        } else {
            throw new Error(`translation unit ${id} is of a kind this script has not been told how to trim`);
        }
    }
    document.units = units;
    return document;
}

/** The files the template is made of, as `{ path, content }`, relative to the template directory. */
function buildTemplate() {
    const plan = planTrim();
    const manifest = readJson(join(SOURCE_DIR, "template.json"));
    const trees = [["content", "en"], ...Object.keys(manifest.contentLocales ?? {}).map(code => [`content.${code}`, code])];
    const files = [];

    for (const [tree, treeLanguage] of trees) {
        const treeDir = join(SOURCE_DIR, tree);
        for (const path of listFiles(treeDir).sort()) {
            const full = join(treeDir, path);
            const blob = ASSET_CONTENT.exec(path);
            if (blob) {
                if (plan.keptAssets.has(assetContentId(blob))) {
                    files.push({ path: `${tree}/${path}`, content: readFileSync(full) });
                }
                continue;
            }
            const original = readFileSync(full, "utf-8");
            let value = null;
            if (ASSET_METADATA.test(path)) {
                value = Object.fromEntries(Object.entries(JSON.parse(original)).filter(([id]) => plan.keptAssets.has(id)));
            } else if (ASSET_ORDER.test(path)) {
                const order = JSON.parse(original);
                value = {
                    ...order,
                    assetIds: order.assetIds.filter(id => plan.keptAssets.has(id)),
                    groupIds: order.groupIds.filter(id => plan.keptGroups.has(id)),
                };
            } else if (ASSET_GROUPS.test(path)) {
                value = Object.fromEntries(Object.entries(JSON.parse(original)).filter(([id]) => plan.keptGroups.has(id)));
            } else if (path === "editor/variables.json") {
                const document = JSON.parse(original);
                document.entries = Object.fromEntries(Object.entries(document.entries).filter(([id]) => plan.keptVariables.has(id)));
                value = document;
            } else if (path === "editor/services/character.json") {
                value = { ...JSON.parse(original), characters: [] };
            } else if (STORY_DOC.test(path)) {
                value = trimStory(JSON.parse(original), plan, treeLanguage);
            } else if (TRANSLATION.test(path) && path !== "editor/localization/keys.json") {
                const fileLanguage = languageOfFile(TRANSLATION.exec(path)[1]);
                value = trimTranslation(JSON.parse(original), plan, treeLanguage, fileLanguage);
            }
            files.push({ path: `${tree}/${path}`, content: value === null ? original : sameFormatJson(original, value) });
        }
    }

    const portManifest = {
        ...MANIFEST_TEXT,
        version: manifest.version,
        designSize: manifest.designSize,
        ...(manifest.designSizes ? { designSizes: manifest.designSizes } : {}),
        ...(manifest.contentLocales ? { contentLocales: manifest.contentLocales } : {}),
        ...(manifest.dependencies ? { dependencies: manifest.dependencies } : {}),
    };
    files.push({ path: "template.json", content: `${JSON.stringify(portManifest, null, 4)}\n` });
    files.push({ path: "README.md", content: README });
    return files;
}

function sameContent(a, b) {
    return Buffer.isBuffer(a) || Buffer.isBuffer(b)
        ? Buffer.compare(Buffer.from(a), Buffer.from(b)) === 0
        : a === b;
}

const check = process.argv.includes("--check");
const files = buildTemplate();
const exists = statSync(TARGET_DIR, { throwIfNoEntry: false })?.isDirectory() ?? false;

if (check) {
    const onDisk = exists ? listFiles(TARGET_DIR).sort() : [];
    const expected = files.map(file => file.path).sort();
    const differences = [
        ...expected.filter(path => !onDisk.includes(path)).map(path => `missing: ${path}`),
        ...onDisk.filter(path => !expected.includes(path)).map(path => `unexpected: ${path}`),
        ...files
            .filter(file => onDisk.includes(file.path)
                && !sameContent(readFileSync(join(TARGET_DIR, file.path), Buffer.isBuffer(file.content) ? undefined : "utf-8"), file.content))
            .map(file => `out of date: ${file.path}`),
    ];
    if (differences.length > 0) {
        console.error(`skeleton-port does not match the skeleton:\n${differences.map(line => `  ${line}`).join("\n")}\nRun node scripts/gen-skeleton-port.mjs to regenerate it.`);
        process.exit(1);
    }
    console.log(`skeleton-port: up to date (${files.length} files)`);
    process.exit(0);
}

// Written from scratch: a file that stopped being part of the template has to stop existing, and
// every byte here is produced from the skeleton anyway.
if (exists) {
    rmSync(TARGET_DIR, { recursive: true });
}
for (const file of files) {
    const target = join(TARGET_DIR, file.path);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, file.content);
}
console.log(`skeleton-port: wrote ${files.length} files to ${relative(process.cwd(), TARGET_DIR)}`);
