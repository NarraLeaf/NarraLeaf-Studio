/**
 * The cherry petal, as a bitmap.
 *
 * ## Why a bitmap and not a shape
 *
 * The other two seeds are lights: a snowflake and a raindrop are round or long, and an ellipse with a
 * soft falloff is not an approximation of them, it is what they look like. A petal is not. It has an
 * outline (ovate, notched at the tip) and it has *tone* across that outline - the tip catches more
 * light than the base, the edge thins, the midrib runs down it. The tone is the half a formula does
 * not give you, and at the sizes sakura renders at (52px across in the near layer at 1080p, 10px in
 * the far one) it is the half that reads.
 *
 * ## Why it is bytes in a source file
 *
 * The same renderer runs in the main process (the bake), in the workspace (the live preview) and in
 * the runtime bundle. A PNG would need a decoder in all three, and the one that does not have one is
 * the bake - no DOM, no `createImageBitmap`. A single channel of raw luminance needs no decoding
 * anywhere, and 64x64 of it is four kilobytes.
 *
 * ## What one byte means
 *
 * How much light this part of the petal adds, before the particle's own depth gain and the seed's
 * tint. Zero is outside the petal. There is no alpha channel here for the same reason the clip has
 * none: everything is light added onto black.
 */

