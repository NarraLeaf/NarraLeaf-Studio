let decoded: Uint8Array | null = null;

/**
 * The sprite, decoded once.
 *
 * Lazily rather than at module load: every host that imports the field builder pays for this table,
 * and a project with no sakura in it should not. Once decoded it is shared - nothing writes to it.
 */
export function petalSprite(): Uint8Array {
    if (decoded) {
        return decoded;
    }
    const binary = typeof atob === "function"
        ? atob(PETAL_SPRITE_BASE64)
        : Buffer.from(PETAL_SPRITE_BASE64, "base64").toString("binary");
    const bytes = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) {
        bytes[i] = binary.charCodeAt(i);
    }
    decoded = bytes;
    return bytes;
}
